-- Baseline PostgreSQL 18 schema for the sqlite-to-postgresql migration.
--
-- Provenance: translated from the schema a fresh SQLite database gets from the current
-- server binary (both the core file and the attached observability file), so it reflects
-- the converged schema instead of the historical CREATE/ALTER sequence.
--
-- Type mapping (affinity preserving, no semantic upgrade):
--   INTEGER/INT/BIGINT/SMALLINT/BOOLEAN -> bigint
--   REAL/DOUBLE/FLOAT                   -> double precision
--   TEXT/VARCHAR/CHAR/CLOB              -> text
--   BLOB                                -> bytea
--   NUMERIC/DECIMAL                     -> numeric
-- Time columns stay integer epoch values; do not convert them to timestamptz.
-- SQLite `INTEGER PRIMARY KEY AUTOINCREMENT` and surrogate `id` primary keys become
-- `bigint GENERATED BY DEFAULT AS IDENTITY` so migrated ids can be inserted explicitly
-- and the sequence is aligned afterwards by the migration tool.
-- Table CHECK constraints are kept verbatim; SQLite `IFNULL` becomes `COALESCE`.
--
-- Triggers are intentionally not in this baseline: porting them needs PL/pgSQL
-- equivalents for SQLite-only functions (see the trigger port plan at the end of the file).
--
-- Validation: the file applies cleanly to PostgreSQL 18 with ON_ERROR_STOP; the loaded
-- database holds 85 core tables, 38 observability tables, 1092 columns, 39 foreign keys
-- and the same 144 explicit indexes as the SQLite source, with identical column names.
CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS observability;

