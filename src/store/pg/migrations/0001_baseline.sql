-- removed; dropping them silently would break the derived tables they maintain.
--
-- core.trg_upstream_reconciliation_usage_work_insert
-- core.trg_upstream_reconciliation_usage_work_update
-- core.trg_upstream_reconciliation_usage_work_delete
-- core.trg_upstream_reconciliation_work_failure_reset_insert
-- core.trg_upstream_reconciliation_work_failure_reset_update
--   maintain upstream_reconciliation_work from upstream_reconciliation_usage rows.
-- observability.trg_request_logs_canonical_request_kind_insert
-- observability.trg_request_logs_canonical_request_kind_update
--   normalize request_logs.request_kind_key from path, method and request body JSON.
-- observability.trg_dashboard_rollup_source_revision
-- observability.trg_dashboard_rollup_source_revision_delete
--   bump dashboard_rollup_source_revisions buckets and queue day reaudits.
--
-- SQLite-only constructs these need PG equivalents for, each of which must be covered by
-- tests before the trigger port is accepted:
--   json_valid / json_type / json_extract   -> jsonb casts and operators, guarded by a
--                                              validity check that mirrors json_valid
--   strftime('%s','now')                    -> EXTRACT(EPOCH FROM now())::bigint
--   date(x,'unixepoch','localtime','+1 day')-> local-day math on epoch integers, using the
--                                              same server timezone contract as the server
--   INSERT OR IGNORE                        -> INSERT ... ON CONFLICT DO NOTHING
--   scalar MIN(a,b) / MAX(a,b)              -> LEAST(a,b) / GREATEST(a,b)
--   ON CONFLICT(...) DO UPDATE with MIN/MAX -> same, with LEAST/GREATEST
